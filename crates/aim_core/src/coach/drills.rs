//! Drill generation: a knowledge-base entry plus the player's level become a scenario,
//! written as TOML with existing building blocks only and checked like any custom file.
//!
//! The level uses the difficulty scale of `scenario::difficulty`: −1 is the easiest drill,
//! +1 the hardest. Each research range in [`DrillParams`] maps linearly onto it: targets
//! shrink, flicks lengthen, speeds rise and lifetimes shorten as the level rises. Every
//! number is an estimate; generated drills are uncalibrated.

use super::knowledge::{DrillParams, KnowledgeEntry, SubSkill};
use crate::scenario::ScenarioDef;
use crate::sim::{AimerProfile, simulate};

/// Prefix of every generated scenario id.
pub const ID_PREFIX: &str = "coach-";
/// Seed of the playability check, the one the built-in sim tests use.
pub const PLAYABILITY_SEED: u64 = 11;

/// Distance of sphere targets, meters (the built-in flick drills use 10–16 m).
const SPHERE_DISTANCE_M: f32 = 12.0;
/// A VALORANT head, as a sphere radius in meters (`docs/valorant-mechanics.md`).
const HEAD_RADIUS_M: f32 = 0.125;

/// The id of the `n`-th generated drill for `skill`: `coach-<skill>-<n>`.
pub fn drill_id(skill: SubSkill, n: u32) -> String {
    format!("{ID_PREFIX}{}-{n}", skill.id())
}

/// The TOML of drill `n` for `skill` at `level` (clamped to [−1, 1]).
pub fn drill_toml(skill: SubSkill, level: f32, n: u32) -> String {
    let entry = skill.entry();
    let t = (level.clamp(-1.0, 1.0) + 1.0) / 2.0;
    let d = &entry.drill;
    let header = header(entry, level.clamp(-1.0, 1.0), n);
    let body = match skill {
        SubSkill::FlickAccuracy => flicks(d, t, 20),
        SubSkill::MicroAdjustment => flicks(d, t, 25),
        SubSkill::ClickTiming => click_timing(d, t),
        SubSkill::ReactiveAcquisition => reactive_acquisition(d, t),
        SubSkill::SmoothTracking => smooth_tracking(d, t),
        SubSkill::ReactiveTracking => reactive_tracking(t),
        SubSkill::TargetSwitching => switching(d, t),
        SubSkill::CrosshairPlacement => crosshair_placement(d, t),
        SubSkill::MovingShots => moving_shots(d, t),
        SubSkill::PeekAndHold => peek_and_hold(d, t),
    };
    format!("{header}{body}")
}

/// Drill `n` for `skill` at `level`, parsed and validated. Errors are the parser's or
/// `validate()`'s messages; a valid knowledge base never produces any (tested).
pub fn generate(skill: SubSkill, level: f32, n: u32) -> Result<ScenarioDef, Vec<String>> {
    parse_and_validate(&drill_toml(skill, level, n))
}

/// Parse `toml` as a scenario and run `validate()`, collecting every problem as text.
pub fn parse_and_validate(toml: &str) -> Result<ScenarioDef, Vec<String>> {
    let def = ScenarioDef::from_toml(toml).map_err(|e| vec![e.to_string()])?;
    let errors: Vec<String> = def
        .validate()
        .into_iter()
        .map(|e| format!("{}: {}", e.field, e.message))
        .collect();
    if errors.is_empty() {
        Ok(def)
    } else {
        Err(errors)
    }
}

/// The playability gate of the built-in library: the simulated contender must score.
/// Returns its score, or why the drill is not playable.
pub fn check_playable(def: &ScenarioDef) -> Result<f32, String> {
    let contender = AimerProfile::PRESETS[1];
    let score = simulate(def, contender, PLAYABILITY_SEED).score;
    if score > 0.0 {
        Ok(score)
    } else {
        Err(format!(
            "not playable: the simulated contender scored {score:.0}; make targets bigger, \
             slower or longer-lived"
        ))
    }
}

fn lerp(range: (f32, f32), t: f32) -> f32 {
    range.0 + (range.1 - range.0) * t
}

/// From the easy end (`range.1`) down to the hard end (`range.0`) as `t` rises.
fn shrink(range: (f32, f32), t: f32) -> f32 {
    lerp((range.1, range.0), t)
}

/// The sphere radius, meters, that spans `radius_deg` at `distance_m`.
fn sphere_radius_m(radius_deg: f32, distance_m: f32) -> f32 {
    distance_m * radius_deg.to_radians().tan()
}

fn field<T>(value: Option<T>, skill: &str) -> T {
    value.unwrap_or_else(|| panic!("the {skill} knowledge entry defines this drill range"))
}

fn header(entry: &KnowledgeEntry, level: f32, n: u32) -> String {
    let category = match entry.skill {
        SubSkill::FlickAccuracy | SubSkill::ClickTiming => "flicking",
        SubSkill::MicroAdjustment | SubSkill::CrosshairPlacement => "microcorrection",
        SubSkill::ReactiveAcquisition | SubSkill::PeekAndHold => "reaction",
        SubSkill::SmoothTracking | SubSkill::ReactiveTracking => "tracking",
        SubSkill::TargetSwitching => "switching",
        SubSkill::MovingShots => "movement",
    };
    format!(
        "id = \"{id}\"\nname = \"Coach: {name} ({level:+.2})\"\ncategory = \"{category}\"\n\
         description = \"\"\"\n{cue}\nGenerated by the AI coach at level {level:+.2}. \
         Uncalibrated: every number is an estimate.\"\"\"\nduration_secs = {secs:.1}\n\n",
        id = drill_id(entry.skill, n),
        name = entry.name,
        cue = entry.cue,
        secs = entry.drill.run_secs,
    )
}

fn flicks(d: &DrillParams, t: f32, miss_penalty: u32) -> String {
    let radius = field(d.target_radius_deg, "flick");
    let offset = field(d.distance_deg, "flick");
    let mid = (offset.0 + offset.1) / 2.0;
    // Micro-adjustment drills stand closer, like the built-in `micro-adjust`.
    let distance = if offset.1 <= 10.0 {
        10.0
    } else {
        SPHERE_DISTANCE_M
    };
    format!(
        "[targets]\nshape = {{ kind = \"sphere\", radius = {r:.3} }}\n\
         spawn = {{ kind = \"around_crosshair\", offset_deg = [{lo:.1}, {hi:.1}], \
         distance = [{distance:.1}, {distance:.1}] }}\n\n[scoring]\nmiss_penalty = {miss_penalty}\n",
        r = sphere_radius_m(shrink(radius, t), distance),
        lo = offset.0,
        hi = lerp((mid, offset.1), t),
    )
}

fn click_timing(d: &DrillParams, t: f32) -> String {
    let radius = field(d.target_radius_deg, "click timing");
    let offset = field(d.distance_deg, "click timing");
    format!(
        "[targets]\nshape = {{ kind = \"sphere\", radius = {r:.3} }}\n\
         spawn = {{ kind = \"around_crosshair\", offset_deg = [{lo:.1}, {hi:.1}], \
         distance = [10.0, 10.0] }}\nlifetime_secs = {life:.2}\n\n\
         [scoring]\nmiss_penalty = 15\nexpire_penalty = 20\n",
        r = sphere_radius_m(shrink(radius, t), 10.0),
        lo = offset.0,
        hi = offset.1,
        life = shrink(field(d.lifetime_secs, "click timing"), t),
    )
}

fn reactive_acquisition(d: &DrillParams, t: f32) -> String {
    let radius = field(d.target_radius_deg, "reactive acquisition");
    let yaw = lerp(field(d.distance_deg, "reactive acquisition"), t);
    let delay = field(d.spawn_delay_secs, "reactive acquisition");
    format!(
        "[targets]\nshape = {{ kind = \"sphere\", radius = {r:.3} }}\n\
         spawn = {{ kind = \"angular\", yaw_deg = [{neg:.1}, {yaw:.1}], pitch_deg = [0.0, 8.0], \
         distance = [{dist:.1}, {dist:.1}] }}\nmax_alive = 1\n\
         appear_delay_secs = [{d0:.2}, {d1:.2}]\nlifetime_secs = {life:.2}\n\n\
         [scoring]\nmiss_penalty = 20\nexpire_penalty = 25\n",
        r = sphere_radius_m(shrink(radius, t), SPHERE_DISTANCE_M),
        neg = -yaw,
        dist = SPHERE_DISTANCE_M,
        d0 = delay.0,
        d1 = delay.1,
        life = shrink(field(d.lifetime_secs, "reactive acquisition"), t),
    )
}

fn smooth_tracking(d: &DrillParams, t: f32) -> String {
    const DISTANCE_M: f32 = 10.0;
    let radius = field(d.target_radius_deg, "smooth tracking");
    let deg_per_sec = lerp(field(d.speed_deg_per_sec, "smooth tracking"), t);
    // Drift speed is linear (m/s); at distance d an angular speed ω needs d·ω.
    let speed = DISTANCE_M * deg_per_sec.to_radians();
    format!(
        "[weapon]\nfire = \"hold\"\n\n[targets]\nshape = {{ kind = \"sphere\", radius = {r:.3} }}\n\
         spawn = {{ kind = \"angular\", yaw_deg = [-10.0, 10.0], pitch_deg = [0.0, 6.0], \
         distance = [{DISTANCE_M:.1}, {DISTANCE_M:.1}] }}\n\
         motion = {{ kind = \"drift\", speed = [{s0:.2}, {s1:.2}], change_secs = [1.0, 2.0], \
         max_offset = 4.0 }}\nhealth = inf\n\n[scoring]\nsphere = 100\n",
        r = sphere_radius_m(shrink(radius, t), DISTANCE_M),
        s0 = speed * 0.9,
        s1 = speed * 1.1,
    )
}

fn reactive_tracking(t: f32) -> String {
    // Agents keep their VALORANT size and stand where `track-reactive-strafe` puts them
    // (closer agents look bigger and are easier to track); reversal timing sets the level.
    format!(
        "[weapon]\nfire = \"hold\"\n\n[targets]\nshape = {{ kind = \"humanoid\" }}\n\
         spawn = {{ kind = \"floor\", x = [-2.0, 2.0], z = [-14.0, -10.0] }}\n\
         motion = {{ kind = \"strafe\", weapon = \"knife\", change_secs = [{c0:.2}, {c1:.2}], \
         stop_chance = {stop:.2}, max_offset = 3.5 }}\nhealth = inf\n\n\
         [scoring]\nhead = 100\nbody = 40\nlegs = 25\n",
        c0 = lerp((0.4, 0.15), t),
        c1 = lerp((0.9, 0.5), t),
        stop = lerp((0.3, 0.1), t),
    )
}

fn switching(d: &DrillParams, t: f32) -> String {
    const DISTANCE_M: f32 = 14.0;
    let radius = field(d.target_radius_deg, "switching");
    let spacing = field(d.distance_deg, "switching");
    let targets = field(d.targets, "switching");
    let alive = lerp((targets.0 as f32, targets.1 as f32), t).round() as u32;
    // Wider spacing means bigger switches; the area keeps room for every target.
    let separation = lerp((spacing.0, (spacing.0 + spacing.1) / 2.0), t);
    format!(
        "[targets]\nshape = {{ kind = \"sphere\", radius = {r:.3} }}\n\
         spawn = {{ kind = \"angular\", yaw_deg = [{neg:.1}, {yaw:.1}], pitch_deg = [-2.0, 10.0], \
         distance = [{DISTANCE_M:.1}, {DISTANCE_M:.1}] }}\nmax_alive = {alive}\n\
         min_separation_deg = {separation:.1}\n\n[scoring]\nmiss_penalty = 15\n",
        r = sphere_radius_m(shrink(radius, t), DISTANCE_M),
        yaw = spacing.1,
        neg = -spacing.1,
    )
}

fn crosshair_placement(d: &DrillParams, t: f32) -> String {
    let targets = field(d.targets, "crosshair placement");
    let alive = lerp((targets.0 as f32, targets.1 as f32), t).round() as u32;
    format!(
        "[targets]\nshape = {{ kind = \"sphere\", radius = {HEAD_RADIUS_M} }}\n\
         spawn = {{ kind = \"floor\", x = [{nx:.1}, {x:.1}], z = [{z:.1}, -9.0], \
         height = [1.8, 1.95] }}\nmax_alive = {alive}\nmin_separation_deg = 4\n\n\
         [scoring]\nmiss_penalty = 25\n",
        x = lerp((6.0, 9.0), t),
        nx = -lerp((6.0, 9.0), t),
        z = -lerp((16.0, 26.0), t),
    )
}

fn moving_shots(d: &DrillParams, t: f32) -> String {
    format!(
        "[weapon]\nkind = \"vandal\"\nsimulate_spread = true\n\n\
         [player]\nmovement = true\nbounds_x = [-8.0, 8.0]\nbounds_z = [-2.0, 5.0]\n\n\
         [targets]\nshape = {{ kind = \"humanoid\", head_only = true }}\n\
         spawn = {{ kind = \"floor\", x = [-9.0, 9.0], z = [-22.0, -12.0] }}\nmax_alive = 1\n\
         lifetime_secs = {life:.2}\n\n\
         [scoring]\nmiss_penalty = 10\nmoving_shot_penalty = 50\nexpire_penalty = 50\n",
        life = shrink(field(d.lifetime_secs, "moving shots"), t),
    )
}

fn peek_and_hold(d: &DrillParams, t: f32) -> String {
    let delay = field(d.spawn_delay_secs, "peek and hold");
    format!(
        "[targets]\nshape = {{ kind = \"humanoid\", head_only = true }}\n\
         spawn = {{ kind = \"angular\", yaw_deg = [{ny:.1}, {y:.1}], pitch_deg = [0.0, 0.0], \
         distance = [15.0, 25.0] }}\n\
         motion = {{ kind = \"strafe\", weapon = \"vandal\", change_secs = [0.3, 0.6], \
         max_offset = 1.5 }}\nmax_alive = 1\nappear_delay_secs = [{d0:.2}, {d1:.2}]\n\
         lifetime_secs = {life:.2}\n\n[scoring]\nmiss_penalty = 25\nexpire_penalty = 50\n",
        y = lerp((6.0, 12.0), t),
        ny = -lerp((6.0, 12.0), t),
        d0 = delay.0,
        d1 = delay.1,
        life = shrink(field(d.lifetime_secs, "peek and hold"), t),
    )
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::scenario::Shape;

    const LEVELS: [f32; 3] = [-1.0, 0.0, 1.0];

    #[test]
    fn every_sub_skill_generates_a_valid_playable_drill_at_every_level() {
        for skill in SubSkill::ALL {
            for level in LEVELS {
                let def = generate(skill, level, 1)
                    .unwrap_or_else(|e| panic!("{skill:?} at {level}: {e:?}"));
                assert_eq!(def.id, format!("coach-{}-1", skill.id()));
                assert!(def.description.contains("Uncalibrated"), "{}", def.id);
                let score =
                    check_playable(&def).unwrap_or_else(|e| panic!("{skill:?} at {level}: {e}"));
                assert!(score > 0.0);
            }
        }
    }

    #[test]
    fn a_higher_level_gives_a_harder_drill() {
        let radius = |level| match generate(SubSkill::FlickAccuracy, level, 1)
            .unwrap()
            .targets
            .shape
        {
            Shape::Sphere { radius } => radius,
            other => unreachable!("flick drills use spheres, not {other:?}"),
        };
        assert!(radius(1.0) < radius(0.0) && radius(0.0) < radius(-1.0));
        let life = |level| {
            generate(SubSkill::ClickTiming, level, 1)
                .unwrap()
                .targets
                .lifetime_secs
                .unwrap()
        };
        assert!((life(-1.0) - 0.9).abs() < 1e-6, "starts at 900 ms");
        assert!(life(1.0) < life(-1.0));
    }

    #[test]
    fn levels_outside_the_scale_are_clamped() {
        assert_eq!(
            drill_toml(SubSkill::SmoothTracking, 7.0, 2),
            drill_toml(SubSkill::SmoothTracking, 1.0, 2)
        );
    }

    #[test]
    fn invalid_toml_reports_parser_and_validation_errors() {
        assert!(parse_and_validate("id = ").is_err());
        let toml = drill_toml(SubSkill::FlickAccuracy, 0.0, 1)
            .replace("duration_secs = 60.0", "duration_secs = -5.0");
        let errors = parse_and_validate(&toml).unwrap_err();
        assert!(
            errors.iter().any(|e| e.starts_with("duration_secs")),
            "{errors:?}"
        );
    }
}
